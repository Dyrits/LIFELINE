#!/usr/bin/env node
// Writes src/career/world.ts: Natural Earth 110m land polygons (public domain) touching a lon/lat box, simplified.
// Usage: node .agents/scripts/generate-world-land.mjs [--box W,S,E,N] [--tolerance DEG] [--out PATH]
import { writeFileSync } from 'node:fs';

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : fallback;
};
const [W, S, E, N] = arg('box', '-25,-55,165,80').split(',').map(Number);
const TOL = Number(arg('tolerance', '0.3'));
const OUT = arg('out', 'src/career/world.ts');
const URL = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';

const geo = await (await fetch(URL)).json();

// Douglas–Peucker on lon/lat, keeping the ring closed.
const simplify = pts => {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a];
    const [bx, by] = pts[b];
    const len = Math.hypot(bx - ax, by - ay);
    let far = -1;
    let dist = TOL;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      // A closed ring starts and ends on the same point: measure from that point instead of a line.
      const d = len ? Math.abs((bx - ax) * (ay - py) - (ax - px) * (by - ay)) / len : Math.hypot(px - ax, py - ay);
      if (d > dist) [far, dist] = [i, d];
    }
    if (far > 0) {
      keep[far] = 1;
      stack.push([a, far], [far, b]);
    }
  }
  return pts.filter((_, i) => keep[i]);
};

const rings = geo.features
  .flatMap(f => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates))
  .map(poly => poly[0])
  .filter(ring => ring.some(([x, y]) => x >= W && x <= E && y >= S && y <= N))
  .map(simplify)
  .filter(ring => ring.length >= 4)
  .map(ring => ring.map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10]));

const body = rings.map(r => `  [${r.map(([x, y]) => `[${x},${y}]`).join(',')}],`).join('\n');
writeFileSync(
  OUT,
  `// Generated by .agents/scripts/generate-world-land.mjs from Natural Earth 110m land (public domain).
// Land outlines touching longitudes ${W} to ${E} and latitudes ${S} to ${N}, as [longitude, latitude] rings.
// biome-ignore format: generated data
export const LAND: readonly (readonly (readonly [lon: number, lat: number])[])[] = [
${body}
];
`,
);
console.log(`${rings.length} rings, ${rings.reduce((n, r) => n + r.length, 0)} points → ${OUT}`);
